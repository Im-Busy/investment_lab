"""Loughran-McDonald financial sentiment dictionary loader and scorer.

The LM dictionary (Loughran & McDonald 2011, JF) categorizes words by
financial-domain sentiment using ~80,000 words from 10-K filings and
earnings call transcripts. Categories:

- Positive: e.g., "achieved", "advantage", "improvement"
- Negative: e.g., "loss", "decline", "default", "termination"
- Uncertainty: e.g., "may", "could", "approximately", "dependent"
- Litigious: e.g., "lawsuit", "plaintiff", "allegation", "breach"

Standard formula: Score = (N_pos - N_neg) / N_total

CSV source: https://sraf.nd.edu/loughranmcdonald-master-dictionary/
"""

