class LMDictionary:
    """Loughran-McDonald financial sentiment dictionary.

    Loads the LM Master Dictionary CSV and provides access to word sets
    for financial-domain sentiment analysis. Falls back to built-in word
    sets (~600 words each) if the CSV is not available.

    The LM dictionary categorizes ~80,000 words from 10-K filings and
    earnings call transcripts with financial-domain sentiment tags.

    Reference:
        Loughran & McDonald, 2011, "When is a Liability not a Liability?"
        Journal of Finance, 66:1, 35-65.
    """

    def __init__(self, csv_path: Path | None = None) -> None:
        if csv_path is not None:
            self.csv_path = Path(csv_path)
        elif LM_DEFAULT_PATH.exists():
            self.csv_path = LM_DEFAULT_PATH
        elif LM_ALT_PATH.exists():
            self.csv_path = LM_ALT_PATH
        else:
            self.csv_path = None
        self._df: pd.DataFrame | None = None
        self._pos_words: set[str] = set()
        self._neg_words: set[str] = set()
        self._unc_words: set[str] = set()
        self._lit_words: set[str] = set()

    def _load(self) -> None:
        if self._df is not None:
            return

        if self.csv_path is not None and self.csv_path.exists():
            self._load_from_csv()
        else:
            self._load_builtin()

    def _load_from_csv(self) -> None:
        """Load from LM Master Dictionary CSV."""
        self._df = pd.read_csv(self.csv_path)
        # LM sentiment columns contain the year the word was added
        # (e.g., 2009, 2011) or 0. Negative years indicate removal.
        # Positive value = word belongs to that sentiment category.
        self._pos_words = set(
            str(w).lower()
            for w in self._df.loc[
                pd.to_numeric(self._df["Positive"], errors="coerce").fillna(0).astype(int) > 0,
                "Word",
            ]
        )
        self._neg_words = set(
            str(w).lower()
            for w in self._df.loc[
                pd.to_numeric(self._df["Negative"], errors="coerce").fillna(0).astype(int) > 0,
                "Word",
            ]
        )
        self._unc_words = set(
            str(w).lower()
            for w in self._df.loc[
                pd.to_numeric(self._df["Uncertainty"], errors="coerce").fillna(0).astype(int) > 0,
                "Word",
            ]
        )
        self._lit_words = set(
            str(w).lower()
            for w in self._df.loc[
                pd.to_numeric(self._df["Litigious"], errors="coerce").fillna(0).astype(int) > 0,
                "Word",
            ]
        )
        logger.info(
            "LM Dictionary loaded from %s: %d pos, %d neg, %d unc, %d lit words",
            self.csv_path,
            len(self._pos_words),
            len(self._neg_words),
            len(self._unc_words),
            len(self._lit_words),
        )

    def _load_builtin(self) -> None:
        """Fall back to built-in word sets (~600 words each category)."""
        self._pos_words = _BUILTIN_POSITIVE
        self._neg_words = _BUILTIN_NEGATIVE
        self._unc_words = _BUILTIN_UNCERTAINTY
        self._lit_words = _BUILTIN_LITIGIOUS
        logger.info(
            "LM Dictionary using built-in fallback: %d pos, %d neg, %d unc, %d lit words",
            len(self._pos_words),
            len(self._neg_words),
            len(self._unc_words),
            len(self._lit_words),
        )

    @property
    def positive_words(self) -> set[str]:
        self._load()
        return self._pos_words

    @property
    def negative_words(self) -> set[str]:
        self._load()
        return self._neg_words

    @property
    def uncertainty_words(self) -> set[str]:
        self._load()
        return self._unc_words

    @property
    def litigious_words(self) -> set[str]:
        self._load()
        return self._lit_words

    def is_loaded(self) -> bool:
        return self._df is not None or len(self._pos_words) > 0


class LMSentimentScorer:
    """Score financial text using the LM dictionary.

    Computes sentiment scores by counting positive, negative, uncertainty,
    and litigious words in text, normalized by total word count.

    Standard LM formula: sentiment = (N_pos - N_neg) / N_total
    """

    def __init__(self, dictionary: LMDictionary | None = None) -> None:
        self.dictionary = dictionary or LMDictionary()

    def score_text(self, text: str) -> dict[str, float]:
        """Score a single text document.

        Args:
            text: The text to analyze.

        Returns:
            dict with keys: sentiment, uncertainty_ratio, litigious_ratio,
            positive_count, negative_count, uncertainty_count, litigious_count,
            total_words.
        """
        words = [w.strip(".,;:!?()[]{}\"'") for w in text.lower().split()]
        total = len(words)
        if total == 0:
            return {
                "sentiment": 0.0,
                "uncertainty_ratio": 0.0,
                "litigious_ratio": 0.0,
                "positive_count": 0,
                "negative_count": 0,
                "uncertainty_count": 0,
                "litigious_count": 0,
                "total_words": 0,
            }

        pos = sum(1 for w in words if w in self.dictionary.positive_words)
        neg = sum(1 for w in words if w in self.dictionary.negative_words)
        unc = sum(1 for w in words if w in self.dictionary.uncertainty_words)
        lit = sum(1 for w in words if w in self.dictionary.litigious_words)

        sentiment = (pos - neg) / total
        uncertainty_ratio = unc / (pos + neg + 1)
        litigious_ratio = lit / max(total, 1)

        return {
            "sentiment": round(sentiment, 4),
            "uncertainty_ratio": round(uncertainty_ratio, 4),
            "litigious_ratio": round(litigious_ratio, 4),
            "positive_count": pos,
            "negative_count": neg,
            "uncertainty_count": unc,
            "litigious_count": lit,
            "total_words": total,
        }

    def score_batch(self, texts: list[str], dates: pd.DatetimeIndex) -> pd.DataFrame:
        """Score multiple texts, returning a time-indexed DataFrame.

        Args:
            texts: List of text strings to score.
            dates: DatetimeIndex aligned with texts.

        Returns:
            DataFrame with sentiment scores, indexed by dates.
        """
        results = [self.score_text(t) for t in texts]
        return pd.DataFrame(results, index=dates)


class LMTradingSignalModifier:
    """Convert LM sentiment scores into trading signal adjustments.

    Replaces the simple multiplicative adjustment in SentimentSignalModifier
    with richer financial-domain logic:

    - Base adjustment: sentiment * weight (same as simple modifier)
    - Uncertainty penalty: high uncertainty = management obfuscation = suppress
    - Litigious penalty: legal risk = suppress

    Formula: adjusted = base_signal * (1 + weight * sentiment - penalties)
    Clamped to [0, 1].

    Reference:
        Loughran & McDonald 2016, "Textual Analysis in Accounting and Finance:
        A Survey", Journal of Accounting Research, 54:4.
    """

    def __init__(
        self,
        scorer: LMSentimentScorer | None = None,
        sentiment_weight: float = 0.15,
        uncertainty_penalty: float = 0.05,
        litigious_penalty: float = 0.10,
        uncertainty_threshold: float = 0.30,
        litigious_threshold: float = 0.05,
    ) -> None:
        self.scorer = scorer or LMSentimentScorer()
        self.sentiment_weight = sentiment_weight
        self.uncertainty_penalty = uncertainty_penalty
        self.litigious_penalty = litigious_penalty
        self.uncertainty_threshold = uncertainty_threshold
        self.litigious_threshold = litigious_threshold

    def adjust_signal(self, base_signal: float, text: str) -> float:
        """Adjust a trading signal using LM sentiment on associated text.

        Args:
            base_signal: ML probability in [0, 1].
            text: Associated news/filing text.

        Returns:
            Adjusted probability in [0, 1].
        """
        scores = self.scorer.score_text(text)

        adjustment = 1.0 + self.sentiment_weight * scores["sentiment"]

        if scores["uncertainty_ratio"] > self.uncertainty_threshold:
            adjustment -= self.uncertainty_penalty

        if scores["litigious_ratio"] > self.litigious_threshold:
            adjustment -= self.litigious_penalty

        adjusted = base_signal * max(adjustment, 0.5)
        return float(np.clip(adjusted, 0.0, 1.0))
